/**
 * Bundled-runtime bootstrap: make a freshly installed desktop "work out of the
 * box" by detecting the DSH runtime that ships *inside* the installer and
 * registering it with the daemon the desktop already spawns.
 *
 * Three things this file is allowed to do, and nothing else:
 *
 *   1. Locate `resources/dsh` + `resources/node` (dev: inside the app path;
 *      packaged: electron-builder `extraResources`).
 *   2. Prove the runtime is usable, by executing it with the Node we shipped:
 *      `--version` (identity) and `--profile headless --dump-default-config`
 *      (the whole cordis boot chain composes). `--list-models` is attempted
 *      too, but DSH has no such flag — it answers
 *      "error: --profile <name> is required". That is recorded as
 *      "unsupported", not treated as a failure, because the flag is a
 *      nice-to-have and misreading it would demote a working runtime.
 *   3. On success, write a runtime profile record and point the existing
 *      daemon registration flow at the bundle by exporting `MULTICA_DSH_PATH`:
 *      `desktopSpawnEnv()` (daemon-manager.ts) spreads `process.env`, and the
 *      daemon's own `probeAgentCLIs` already probes that exact variable
 *      (server/internal/daemon/agents_probe.go) — so no second registration
 *      mechanism is invented here.
 *
 * On failure the UI gets an IPC event and shows the "install the runtime"
 * prompt. Nothing in this path can block sign-in or window creation: the probe
 * is fire-and-forget and every failure is a status, not a throw.
 *
 * Logging rule: paths, versions, durations and booleans only. A credential
 * never reaches this file — the probe environment is built from an explicit
 * allowlist, not from `process.env`.
 */

import { execFile } from "node:child_process";
import { existsSync, statSync } from "node:fs";
import { mkdir, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { app, ipcMain } from "electron";

/** Pushed to every renderer on each state change. */
export const DSH_BOOTSTRAP_STATUS_CHANNEL = "dsh-bootstrap:status";
/** Pulled by a renderer that mounted after the probe finished. */
export const DSH_BOOTSTRAP_GET_CHANNEL = "dsh-bootstrap:get";

/**
 * Budget for one probe command. Ten seconds is not a guess: the boot-chain
 * probe composes the entire profile tree, and a cold Windows VM with an
 * antivirus scanning 13k freshly written files needs far more than the
 * `--version` round trip (measured 366 ms warm, ~2 s cold).
 */
export const DSH_PROBE_TIMEOUT_MS = 10_000;

const DSH_ENTRY_REL = join("node_modules", "@deepseek-ai", "dsh", "lib", "bin.js");
const DSH_VERSION_LINE = /^[0-9]+\.[0-9]+\.[0-9]+[^\s]*$/;

export type DshBootstrapState =
  /** Not started yet. */
  | "idle"
  /** Probe running; UI should not show the install prompt yet. */
  | "probing"
  /** Runtime found, verified and registered with the daemon. */
  | "ready"
  /** No bundled runtime in this build (or a frontend-only build). */
  | "absent"
  /** Bundled files exist but the runtime did not answer. */
  | "failed";

export interface DshBootstrapStatus {
  /** UI text; contains paths and versions, never credential material. */
  readonly detail: string;
  readonly state: DshBootstrapState;
  readonly runtimeId: "dsh";
  /** True when the UI should offer the "install the runtime" wizard. */
  readonly needsInstall: boolean;
  readonly version?: string;
  readonly binaryPath?: string;
  readonly nodePath?: string;
  readonly models?: readonly string[];
  readonly probeMs?: number;
  /** Coarse reason only (`missing-files`, `version-failed`, `boot-failed`). */
  readonly reason?: string;
  readonly updatedAt?: string;
}

/** What the bundle hands the daemon: a command to run, and how to run it. */
export interface BundledDshPaths {
  readonly dshDir: string;
  readonly entryPath: string;
  readonly nodePath: string;
  /**
   * Executable shim (`bin/dsh.cmd` / `bin/dsh`) generated by
   * `scripts/bundle-dsh.mjs`. `MULTICA_DSH_PATH` must point at something the
   * daemon can *execute*, and `bin.js` is a Node script, so this is the value
   * that gets exported.
   */
  readonly commandPath: string;
}

export interface DshProbeResult {
  readonly ok: boolean;
  readonly reason?: "missing-files" | "version-failed" | "boot-failed";
  readonly version?: string;
  readonly bootChainEntries?: number;
  readonly listModelsSupported?: boolean;
  readonly models?: readonly string[];
  /** Truncated child output, safe for a log line: it is a CLI error, not data. */
  readonly error?: string;
  readonly probeMs?: number;
}

export interface DshRuntimeProfileRecord {
  readonly schemaVersion: 1;
  readonly id: "dsh";
  readonly kind: "bundled";
  /** Executable the daemon should use (the generated shim). */
  readonly command: string;
  /** Node entry point the shim runs. */
  readonly entry: string;
  readonly nodePath: string;
  readonly version: string;
  readonly models: readonly string[];
  readonly probe: {
    readonly versionMs: number;
    readonly bootChainOk: boolean;
    readonly bootChainEntries: number;
    readonly listModelsSupported: boolean;
  };
  readonly detectedAt: string;
}

export interface DshBootstrapOptions {
  /** `<userData>`; the runtime profile record is written under it. */
  readonly userDataDir: string;
  readonly env?: NodeJS.ProcessEnv;
  readonly notify?: (status: DshBootstrapStatus) => void;
  readonly logger?: {
    readonly info: (message: string, fields?: Record<string, unknown>) => void;
    readonly warn: (message: string, fields?: Record<string, unknown>) => void;
  };
  readonly now?: () => Date;
  /** Set to false in tests that must not spawn a child process. */
  readonly probe?: (paths: BundledDshPaths) => Promise<DshProbeResult>;
  /** Overrides for tests / non-Electron hosts. */
  readonly resolvePaths?: () => BundledDshPaths | null;
}

export interface DshBootstrapHandle {
  /** Synchronous registration + fire-and-forget probe. Never throws. */
  readonly start: () => Promise<DshBootstrapStatus>;
  readonly status: () => DshBootstrapStatus;
  readonly refresh: () => Promise<DshBootstrapStatus>;
}

function nodeBinaryName(): string {
  return process.platform === "win32" ? "node.exe" : "node";
}

function shimName(): string {
  return process.platform === "win32" ? "dsh.cmd" : "dsh";
}

/**
 * Where the bundle lives at runtime.
 *
 * - Dev (`electron-vite dev`): `app.getAppPath()` is `apps/desktop`, and
 *   `scripts/bundle-dsh.mjs` populated `resources/` before Electron started —
 *   same convention as `bundledCliPath()` for `resources/bin/multica`.
 * - Packaged: `extraResources` copies both trees to `<resources>/dsh` and
 *   `<resources>/node`, which is `process.resourcesPath`. The `app.asar`
 *   rewrite is kept for the case where someone re-adds them to `files/`
 *   instead (then they land in `app.asar.unpacked`).
 */
export function resolveBundledDshPaths(): BundledDshPaths | null {
  const root = app.getAppPath().replace("app.asar", "app.asar.unpacked");
  const candidates = [
    join(process.resourcesPath ?? "", "dsh"),
    join(root, "resources", "dsh"),
  ];
  for (const dshDir of candidates) {
    if (!dshDir) continue;
    const entryPath = join(dshDir, DSH_ENTRY_REL);
    const commandPath = join(dshDir, "bin", shimName());
    const nodePath = join(dirname(dshDir), "node", nodeBinaryName());
    if (existsSync(entryPath) && existsSync(commandPath) && existsSync(nodePath)) {
      return { dshDir, entryPath, nodePath, commandPath };
    }
  }
  return null;
}

/**
 * Environment allowlist for a probe child.
 *
 * Deliberately does *not* forward `MULTICA_RELAY_KEY`, `DEEPSEEK_API_KEY` or
 * anything else that could be a credential: a version probe needs PATH and a
 * scratch `DSH_HOME`, nothing more. `DSH_HOME` points at a throwaway directory
 * so the probe can never read — or create — the user's real DSH home.
 */
function probeEnv(dshHome: string): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = { DSH_HOME: dshHome };
  for (const name of [
    "PATH",
    "Path",
    "SystemRoot",
    "SYSTEMROOT",
    "windir",
    "TEMP",
    "TMP",
    "TMPDIR",
    "HOME",
    "USERPROFILE",
    "APPDATA",
    "LOCALAPPDATA",
    "PROGRAMDATA",
    "LANG",
    "LC_ALL",
  ]) {
    const value = process.env[name];
    if (typeof value === "string" && value.length > 0) env[name] = value;
  }
  return env;
}

interface CommandOutcome {
  readonly ok: boolean;
  readonly stdout: string;
  readonly stderr: string;
  readonly timedOut: boolean;
  readonly error?: string;
  readonly ms: number;
}

function runCommand(
  file: string,
  args: readonly string[],
  env: NodeJS.ProcessEnv,
): Promise<CommandOutcome> {
  const startedAt = Date.now();
  return new Promise((resolve) => {
    execFile(
      file,
      [...args],
      { timeout: DSH_PROBE_TIMEOUT_MS, env, windowsHide: true, maxBuffer: 8 * 1024 * 1024 },
      (error, stdout, stderr) => {
        const timedOut = Boolean(error && error.killed);
        resolve({
          ok: !error,
          stdout: stdout ?? "",
          stderr: stderr ?? "",
          timedOut,
          ...(error ? { error: error.message } : {}),
          ms: Date.now() - startedAt,
        });
      },
    );
  });
}

function firstLine(text: string): string {
  return text.split(/\r?\n/, 1)[0]?.trim() ?? "";
}

function clip(text: string, limit = 240): string {
  const single = text.replace(/\s+/g, " ").trim();
  return single.length > limit ? `${single.slice(0, limit)}…` : single;
}

/**
 * Executes the bundle. Order matters: `--version` is the cheap identity check,
 * the boot-chain composition is the real "can this thing start" check, and
 * `--list-models` is optional (DSH does not implement it — see the module
 * comment).
 */
export async function probeBundledDsh(paths: BundledDshPaths): Promise<DshProbeResult> {
  const dshHome = join(tmpdir(), `morechat-dsh-probe-${process.pid}-${Date.now()}`);
  await mkdir(dshHome, { recursive: true }).catch(() => {});
  try {
    const env = probeEnv(dshHome);
    const versionRun = await runCommand(paths.nodePath, [paths.entryPath, "--version"], env);
    const version = firstLine(versionRun.stdout);
    if (!versionRun.ok || !DSH_VERSION_LINE.test(version)) {
      return {
        ok: false,
        reason: "version-failed",
        probeMs: versionRun.ms,
        error: clip(
          versionRun.timedOut
            ? `timed out after ${DSH_PROBE_TIMEOUT_MS}ms`
            : versionRun.stderr || versionRun.stdout || versionRun.error || "no output",
        ),
      };
    }

    const bootRun = await runCommand(
      paths.nodePath,
      [paths.entryPath, "--profile", "headless", "--dump-default-config"],
      env,
    );
    const bootChainEntries = bootRun.stdout.split(/\r?\n/).filter((line) => line.startsWith("- id: ")).length;
    if (!bootRun.ok || bootChainEntries === 0) {
      return {
        ok: false,
        reason: "boot-failed",
        version,
        probeMs: versionRun.ms + bootRun.ms,
        error: clip(
          bootRun.timedOut
            ? `timed out after ${DSH_PROBE_TIMEOUT_MS}ms`
            : bootRun.stderr || bootRun.stdout || bootRun.error || "no output",
        ),
      };
    }

    // Best effort. A non-zero exit here is expected on today's DSH
    // ("error: --profile <name> is required") and proves only that the flag is
    // absent, not that the runtime is broken.
    const modelsRun = await runCommand(paths.nodePath, [paths.entryPath, "--list-models"], env);
    const models = modelsRun.ok
      ? modelsRun.stdout
          .split(/\r?\n/)
          .map((line) => line.trim())
          .filter((line) => line.length > 0 && !line.startsWith("#"))
      : [];

    return {
      ok: true,
      version,
      bootChainEntries,
      listModelsSupported: modelsRun.ok,
      models,
      ...(modelsRun.ok ? {} : { error: clip(firstLine(modelsRun.stderr) || "list-models unsupported") }),
      probeMs: versionRun.ms + bootRun.ms + modelsRun.ms,
    };
  } finally {
    await rm(dshHome, { recursive: true, force: true }).catch(() => {});
  }
}

/** `<userData>/runtime-profiles/dsh.json` — the record the app reads back. */
export function dshRuntimeProfilePath(userDataDir: string): string {
  return join(userDataDir, "runtime-profiles", "dsh.json");
}

async function writeRuntimeProfile(
  userDataDir: string,
  record: DshRuntimeProfileRecord,
): Promise<string> {
  const target = dshRuntimeProfilePath(userDataDir);
  await mkdir(dirname(target), { recursive: true });
  const temp = `${target}.${process.pid}.tmp`;
  await writeFile(temp, `${JSON.stringify(record, null, 2)}\n`, { mode: 0o644 });
  await rename(temp, target);
  return target;
}

function consoleLogger(): NonNullable<DshBootstrapOptions["logger"]> {
  const write =
    (level: "info" | "warn") => (message: string, fields?: Record<string, unknown>) => {
      const suffix = fields && Object.keys(fields).length > 0 ? ` ${JSON.stringify(fields)}` : "";
      // Fields are paths, versions, counts and durations — never content.
      console[level](`[dsh-bootstrap] ${message}${suffix}`);
    };
  return { info: write("info"), warn: write("warn") };
}

export function installDshBootstrap(options: DshBootstrapOptions): DshBootstrapHandle {
  const logger = options.logger ?? consoleLogger();
  const now = options.now ?? (() => new Date());
  const resolvePaths = options.resolvePaths ?? resolveBundledDshPaths;
  const probe = options.probe ?? probeBundledDsh;

  let registered: BundledDshPaths | null = null;
  let status: DshBootstrapStatus = {
    state: "idle",
    runtimeId: "dsh",
    needsInstall: false,
    detail: "尚未探测本地 DSH 运行时",
  };

  function publish(next: DshBootstrapStatus): DshBootstrapStatus {
    status = next;
    try {
      options.notify?.(status);
    } catch (err) {
      logger.warn("status notify failed", {
        error: err instanceof Error ? err.message : String(err),
      });
    }
    return status;
  }

  /**
   * Hands the bundle to the existing daemon registration flow. `desktopSpawnEnv`
   * spreads `process.env`, and the daemon reads `MULTICA_DSH_PATH`, so exporting
   * it here is the registration — no second config file, no second truth.
   */
  /**
   * The daemon may start with zero detected CLIs only while it is installing a
   * DSH runtime profile from `MULTICA_DSH_PROFILE_BUNDLE`
   * (server/internal/daemon/config.go). Our bundle ships that directory next to
   * the runtime, so point the variable at it when it exists; without it the
   * daemon has to see a working `dsh` on PATH or it refuses to start.
   */
  function profileBundleDir(paths: BundledDshPaths): string | null {
    const resources = resolve(dirname(paths.commandPath), "..", "..");
    const candidate = join(resources, "dsh-profile");
    try {
      return statSync(candidate).isDirectory() ? candidate : null;
    } catch {
      return null;
    }
  }

  function registerEnv(paths: BundledDshPaths): void {
    const env = options.env ?? process.env;
    env.MULTICA_DSH_PATH = paths.commandPath;
    const profileDir = profileBundleDir(paths);
    if (profileDir) env.MULTICA_DSH_PROFILE_BUNDLE = profileDir;
    const prepend = [dirname(paths.commandPath), dirname(paths.nodePath)];
    const current = env.PATH ?? env.Path ?? "";
    const parts = current.split(process.platform === "win32" ? ";" : ":");
    for (const dir of prepend.reverse()) {
      if (!parts.some((part) => part.toLowerCase() === dir.toLowerCase())) parts.unshift(dir);
    }
    env.PATH = parts.join(process.platform === "win32" ? ";" : ":");
    registered = paths;
  }

  function unregisterEnv(): void {
    const env = options.env ?? process.env;
    if (registered && env.MULTICA_DSH_PATH === registered.commandPath) {
      delete env.MULTICA_DSH_PATH;
    }
    delete env.MULTICA_DSH_PROFILE_BUNDLE;
    registered = null;
  }

  async function refresh(): Promise<DshBootstrapStatus> {
    const paths = resolvePaths();
    if (!paths) {
      unregisterEnv();
      logger.info("no bundled runtime", { expected: "resources/dsh + resources/node" });
      return publish({
        state: "absent",
        runtimeId: "dsh",
        needsInstall: true,
        detail: "安装包内没有 DSH 运行时，请点击“安装运行时”",
        reason: "missing-files",
        updatedAt: now().toISOString(),
      });
    }

    registerEnv(paths);
    logger.info("probing bundled runtime", {
      command: paths.commandPath,
      entry: paths.entryPath,
      node: paths.nodePath,
      timeout_ms: DSH_PROBE_TIMEOUT_MS,
    });
    publish({
      state: "probing",
      runtimeId: "dsh",
      needsInstall: false,
      detail: "正在探测内置 DSH 运行时…",
      binaryPath: paths.commandPath,
      nodePath: paths.nodePath,
    });

    let result: DshProbeResult;
    try {
      result = await probe(paths);
    } catch (err) {
      result = {
        ok: false,
        reason: "version-failed",
        error: err instanceof Error ? err.message : String(err),
      };
    }

    if (!result.ok || !result.version) {
      // The env var is withdrawn again: advertising a binary the daemon cannot
      // start would put a permanently "broken" DSH runtime in the UI.
      unregisterEnv();
      logger.warn("bundled runtime unusable", {
        command: paths.commandPath,
        reason: result.reason ?? "unknown",
        error: result.error ?? "",
        probe_ms: result.probeMs ?? 0,
      });
      return publish({
        state: "failed",
        runtimeId: "dsh",
        needsInstall: true,
        detail: `内置 DSH 运行时不可用（${result.reason ?? "unknown"}），请安装运行时后重试`,
        reason: result.reason ?? "unknown",
        binaryPath: paths.commandPath,
        nodePath: paths.nodePath,
        ...(result.probeMs !== undefined ? { probeMs: result.probeMs } : {}),
        updatedAt: now().toISOString(),
      });
    }

    const detectedAt = now().toISOString();
    const record: DshRuntimeProfileRecord = {
      schemaVersion: 1,
      id: "dsh",
      kind: "bundled",
      command: paths.commandPath,
      entry: paths.entryPath,
      nodePath: paths.nodePath,
      version: result.version,
      models: result.models ?? [],
      probe: {
        versionMs: result.probeMs ?? 0,
        bootChainOk: true,
        bootChainEntries: result.bootChainEntries ?? 0,
        listModelsSupported: result.listModelsSupported === true,
      },
      detectedAt,
    };
    const recordPath = await writeRuntimeProfile(options.userDataDir, record).catch(
      (err: unknown) => {
        logger.warn("runtime profile write failed", {
          error: err instanceof Error ? err.message : String(err),
        });
        return null;
      },
    );

    logger.info("registered bundled runtime", {
      runtime: "dsh",
      version: result.version,
      command: paths.commandPath,
      profile: recordPath ?? "(not written)",
      boot_chain_entries: result.bootChainEntries ?? 0,
      list_models_supported: result.listModelsSupported === true,
      probe_ms: result.probeMs ?? 0,
      env: "MULTICA_DSH_PATH",
    });

    return publish({
      state: "ready",
      runtimeId: "dsh",
      needsInstall: false,
      detail: `已注册内置 DSH 运行时 ${result.version}`,
      version: result.version,
      binaryPath: paths.commandPath,
      nodePath: paths.nodePath,
      models: result.models ?? [],
      ...(result.probeMs !== undefined ? { probeMs: result.probeMs } : {}),
      updatedAt: detectedAt,
    });
  }

  ipcMain.removeHandler(DSH_BOOTSTRAP_GET_CHANNEL);
  ipcMain.handle(DSH_BOOTSTRAP_GET_CHANNEL, () => status);

  return {
    async start() {
      try {
        return await refresh();
      } catch (err) {
        // Fail open: a broken probe must never keep a window from opening.
        logger.warn("bootstrap failed", {
          error: err instanceof Error ? err.message : String(err),
        });
        return publish({
          state: "failed",
          runtimeId: "dsh",
          needsInstall: true,
          detail: "探测内置 DSH 运行时失败，请重试或用“安装运行时”",
          reason: "unexpected",
          updatedAt: now().toISOString(),
        });
      }
    },
    status: () => status,
    refresh,
  };
}
