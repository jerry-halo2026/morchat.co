/**
 * DSH target — the `multica` profile's user patch layer.
 *
 * Facts this writer is built on (read out of the shipped DSH bundle, not
 * guessed):
 *   - the daemon launches `dsh --profile multica --stdio`
 *     (server/pkg/agent/dsh.go:119), and profiles live at
 *     `$DSH_HOME/profiles/<profile>/` (DSH_HOME defaults to `~/.dsh`)
 *     (server/internal/daemon/dsh_profile.go:117-131);
 *   - inside a profile, `cordis.yml` is the generated layer — the bundle's own
 *     header says "Edit cordis.patch.yml, not this file" — and
 *     `$DSH_HOME/cordis.patch.yml` is the home-level user patch layer;
 *   - provider credentials are `apiKeyEnv` credential-refs, i.e. DSH reads the
 *     key out of the named environment variable (`dsh-llm-deepseek-api-key`
 *     defaults it to `DEEPSEEK_API_KEY`).
 *
 * Therefore: we never edit `profiles/multica/cordis.yml` (regenerated by the
 * profile install) and we never put a key here. We add a provider entry whose
 * `apiKeyEnv` names the relay key, and the value travels as an env var.
 *
 * Model ids are `provider/model`, URL-escaped, because that is the wire shape
 * the daemon parses (dsh.go:123 `parseDshModelID`).
 */

import type {
  FileSnapshot,
  PlannedFile,
  VerifyFailure,
  VerifyResult,
} from "../types";
import { isYamlRecord, parseYaml } from "../yaml-lite";
import {
  YAML_REGION,
  assertNoSecretLiteral,
  envNameFor,
  file,
  modeTooOpen,
  splitRegion,
  wrapRegion,
  type RuntimeTargetWriter,
  type WriterInput,
} from "./writer";

export const DSH_PROVIDER_ID = "morechat";

/** `provider/model`, with each half escaped the way the daemon expects. */
export function dshModelId(providerId: string, model: string): string {
  return `${encodeURIComponent(providerId)}/${encodeURIComponent(model)}`;
}

export function renderDshRegion(input: WriterInput): string {
  const { provider } = input;
  const envKey = envNameFor(provider.apiKeyRef, "MULTICA_RELAY_KEY");
  // Authoritative shape (verified against the installed harness):
  // `@deepseek-ai/dsh-llm-pi-ai` takes a `providers` dict whose keys are the
  // route names a request selects with `GenerateOptions.provider`; each route
  // carries `api` / `baseURL` / `apiKeyEnv` / `models`. `apiKeyEnv` is only a
  // credential *reference*, so this file never holds a key. The older guess of
  // a top-level `llm-<provider>:` mapping does not exist in the harness.
  // The shape the harness actually loads. Verified with
  // `dsh --profile multica --dump-config`, which shows `llm-deepseek` carrying
  // `baseURL` and `apiKeyEnv`; the api-key plugin registers the same provider id as
  // the account plugin, so model ids stay `deepseek-official/<model>`.
  const body = [
    "# Provider entry for the morechat relay. The key is an env credential-ref:",
    "# its value lives in the harness credential store, never in this file.",
    "- id: llm-deepseek",
    "  config:",
    `    baseURL: ${yamlScalar(provider.baseUrl)}`,
    `    apiKeyEnv: ${yamlScalar(envKey)}`,
    "    models:",
    `      - id: ${yamlScalar(provider.defaultModel)}`,
    `        name: ${yamlScalar(provider.defaultModel)}`,
    "        contextWindow: 131072",
    "        maxTokens: 8192",
  ].join("\n");
  const rendered = wrapRegion(body);
  assertNoSecretLiteral(rendered);
  return rendered;
}

function yamlScalar(value: string): string {
  // Single-quoted YAML needs only the quote doubled; URLs and model ids are
  // otherwise safe, and quoting unconditionally keeps `:` out of trouble.
  return `'${value.replace(/'/g, "''")}'`;
}

function pluginId(): string {
  return "llm-deepseek";
}

/** Our plugin entry inside the patch sequence, if it is still there. */
function findProviderEntry(document: unknown): Record<string, unknown> | null {
  if (!Array.isArray(document)) return null;
  for (const item of document) {
    if (isYamlRecord(item) && item["id"] === pluginId()) return item;
  }
  return null;
}

/**
 * The values we intended to land, read back out of our own rendered region —
 * parsed, so a mismatch means the *document* changed, not the whitespace.
 */
function readPlannedDshValues(content: string): Map<string, unknown> {
  const entry = findProviderEntry(parseYaml(content));
  const provider = isYamlRecord(entry?.config) ? entry.config : undefined;
  const models = isYamlRecord(provider) ? provider["models"] : undefined;
  const firstModel = Array.isArray(models) ? models[0] : undefined;
  return new Map<string, unknown>([
    ["baseURL", isYamlRecord(provider) ? provider["baseURL"] : undefined],
    ["apiKeyEnv", isYamlRecord(provider) ? provider["apiKeyEnv"] : undefined],
    ["model", isYamlRecord(firstModel) ? firstModel["id"] : undefined],
  ]);
}

export const dshWriter: RuntimeTargetWriter = {
  id: "dsh",

  plan(input: WriterInput): readonly PlannedFile[] {
    const target = input.profile.targets.find((t) => t.id === "dsh");
    if (!target) return [];
    const paths = target.paths as { home: string; profileName: string };
    // The home-level patch layer, not the profile's generated cordis.yml.
    return [
      file(
        "dsh",
        joinPath(paths.home, "cordis.patch.yml"),
        "yaml",
        renderDshRegion(input),
        {
          mode: 0o600,
          change: "patch",
          merge: "managed-region",
          managedRegion: YAML_REGION,
        },
      ),
    ];
  },

  verify(
    planned: readonly PlannedFile[],
    snapshot: (path: string) => FileSnapshot,
  ): VerifyResult {
    const failures: VerifyFailure[] = [];
    for (const plannedFile of planned) {
      const landed = snapshot(plannedFile.path);
      if (landed.content === null) {
        failures.push({ code: "missing", path: plannedFile.path });
        continue;
      }

      const region = plannedFile.managedRegion ?? YAML_REGION;
      if (splitRegion(landed.content, region) === null) {
        failures.push({ code: "missing", path: plannedFile.path });
        continue;
      }

      // Parse the whole document: our region is a sequence item, so it can only
      // be valid as part of a document that parses as a whole.
      let document: unknown;
      try {
        document = parseYaml(landed.content);
      } catch (err) {

        failures.push({
          code: "unparsable",
          path: plannedFile.path,
          detail: err instanceof Error ? err.message : String(err),
        });
        continue;
      }

      const entry = findProviderEntry(document);
      if (!entry) {
        failures.push({
          code: "field-mismatch",
          path: plannedFile.path,
          field: `[id=${pluginId()}]`,
        });
        continue;
      }

      const plannedValues = readPlannedDshValues(plannedFile.content);
      // The provider's own config object: `llm-deepseek` takes baseURL/apiKeyEnv
      // directly, which is the shape the harness documents and what
      // `--dump-config` shows for a working profile.
      const provider = isYamlRecord(entry.config) ? entry.config : undefined;
      if (!isYamlRecord(provider)) {
        failures.push({
          code: "field-mismatch",
          path: plannedFile.path,
          field: "config",
        });
        continue;
      }

      const checks: readonly (readonly [string, unknown, string])[] = [
        ["baseURL", provider["baseURL"], "baseURL"],
        ["apiKeyEnv", provider["apiKeyEnv"], "apiKeyEnv"],
      ];
      for (const [field, value, key] of checks) {
        if (value !== plannedValues.get(key)) {
          failures.push({ code: "field-mismatch", path: plannedFile.path, field });
        }
      }

      const models = provider["models"];
      const firstModel = Array.isArray(models) ? models[0] : undefined;
      const firstModelId = isYamlRecord(firstModel) ? firstModel["id"] : undefined;
      if (firstModelId !== plannedValues.get("model")) {
        failures.push({
          code: "field-mismatch",
          path: plannedFile.path,
          field: "config.providers.morechat.models[0].id",
        });
      }

      if (landed.mode !== null && modeTooOpen(landed.mode, plannedFile.mode)) {
        failures.push({
          code: "mode-too-open",
          path: plannedFile.path,
          mode: landed.mode,
        });
      }
    }
    return failures.length === 0 ? { ok: true } : { ok: false, failures };
  },
};

function joinPath(...parts: readonly string[]): string {
  return parts
    .map((part, index) =>
      index === 0 ? part.replace(/[\\/]+$/, "") : part.replace(/^[\\/]+|[\\/]+$/g, ""),
    )
    .join("/");
}

export default dshWriter;
