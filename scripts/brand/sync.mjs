#!/usr/bin/env node
// Writes every text copy of the brand geometry from packages/ui/lib/morechat-brand.ts:
// favicons, the PWA icon source, the README wordmark SVGs, the mobile wordmark and
// the inline SVG on the `multica login` callback page.
//
//   node scripts/brand/sync.mjs           rewrite the copies
//   node scripts/brand/sync.mjs --check   exit 1 if any copy drifted (CI)
//
// Dependency-free on purpose: CI runs it without installing node_modules.
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const INK = "#0b0b0c";
export const PAPER = "#ffffff";
const CLI_WORDMARK_HEIGHT = 19.5;

export async function loadBrand(root) {
  return import(pathToFileURL(join(root, "packages/ui/lib/morechat-brand.ts")).href);
}

export function svgs(brand) {
  const {
    WORDMARK,
    WORDMARK_STROKE,
    ICON_TILE_RADIUS,
    ICON_BARS,
    ICON_TILE_FILL,
    ICON_BAR_FILL,
    iconBarTransform,
  } = brand;

  // The icon's three bars, in the tile's own coordinate space. Each leans about
  // its own centre so the gaps stay as the geometry defines them.
  const bars = ICON_BARS.map(
    (bar) =>
      `<rect x="${bar.x}" y="${bar.y}" width="${bar.width}" height="${bar.height}" rx="${bar.rx}" fill="${ICON_BAR_FILL}" fill-opacity="${bar.opacity}" transform="${iconBarTransform(bar)}"/>`,
  ).join("");

  const tile = (px, { bleed = false } = {}) =>
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="${px}" height="${px}" role="img" aria-label="morechat.co"><rect width="100" height="100"${bleed ? "" : ` rx="${ICON_TILE_RADIUS}"`} fill="${ICON_TILE_FILL}"/>${bars}</svg>`;

  const wordmark = (color, extra = "") =>
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${WORDMARK.viewBox}" role="img" aria-label="morechat.co"${extra}><g fill="none" stroke="${color}" stroke-width="${WORDMARK_STROKE}">${WORDMARK.letters
      .map((letter) => (letter.d ? `<path d="${letter.d}"/>` : ""))
      .join("")}</g>${WORDMARK.letters
      .map((letter) =>
        letter.dot
          ? `<circle cx="${letter.dot.cx}" cy="${letter.dot.cy}" r="${letter.dot.r}" fill="${color}"/>`
          : "",
      )
      .join("")}</svg>`;

  const [, , vbW, vbH] = WORDMARK.viewBox.split(" ").map(Number);
  return {
    tile,
    wordmark,
    favicon: `${tile(100)}\n`,
    pwaIcon: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" role="img" aria-label="morechat.co">
  <!--
    Full-bleed source for the generated home-screen icons (apple-touch-icon.png,
    icon-maskable-512.png). Full-bleed because both surfaces mask the artwork
    themselves: iOS rounds the corners, Android crops to the launcher shape.
    Geometry is packages/ui/lib/morechat-brand.ts (ICON_BARS).
  --><rect width="100" height="100" fill="${ICON_TILE_FILL}"/>${bars}</svg>\n`,
    cliWordmark: wordmark("currentColor", ` height="${CLI_WORDMARK_HEIGHT}" width="${Math.round((CLI_WORDMARK_HEIGHT * vbW) / vbH)}"`),
  };
}

function mobileBlock({ WORDMARK, WORDMARK_STROKE }) {
  const [x, y, w, h] = WORDMARK.viewBox.split(" ").map(Number);
  const letters = WORDMARK.letters.filter((letter) => letter.d);
  const dots = WORDMARK.letters.filter((letter) => letter.dot).map((letter) => letter.dot);
  return [
    `const VIEW_BOX = { x: ${x}, y: ${y}, w: ${w}, h: ${h} };`,
    `const STROKE = ${WORDMARK_STROKE};`,
    "const LETTERS = [",
    ...letters.map((letter) => `  "${letter.d}",`),
    "];",
    "/** The separator dot: the pen's own width, filled. */",
    "const DOTS = [",
    ...dots.map((dot) => `  { cx: ${dot.cx}, cy: ${dot.cy}, r: ${dot.r} },`),
    "];",
  ].join("\n");
}

const MOBILE_BEGIN = "// BEGIN GENERATED by scripts/brand/sync.mjs from WORDMARK in packages/ui/lib/morechat-brand.ts";
const MOBILE_END = "// END GENERATED";
const CLI_SVG = /(<div class="brand">)<svg[^]*?<\/svg>(<\/div>)/;

function splice(text, file, re, body) {
  if (!re.test(text)) throw new Error(`${file}: cannot find the generated wordmark`);
  // Windows checkouts hold CRLF (core.autocrlf), the generated block is written
  // with LF: keep whatever the file already uses so the diff stays about content.
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  return text.replace(re, (_, open, close) => open + body.replace(/\n/g, eol) + close);
}

/** Every synced file as `[path relative to root, expected content]`. */
export async function targets(root) {
  const brand = await loadBrand(root);
  const s = svgs(brand);
  const read = (rel) => readFileSync(join(root, rel), "utf8");
  const mobile = "apps/mobile/components/brand/multica-logo.tsx";
  const cli = "server/cmd/multica/cmd_auth.go";
  const between = new RegExp(
    `(${escapeRe(MOBILE_BEGIN)}\\r?\\n)[^]*?(\\r?\\n${escapeRe(MOBILE_END)})`,
  );
  return [
    ["apps/web/public/favicon.svg", s.favicon],
    ["apps/web/app/icon.svg", s.favicon],
    ["apps/docs/app/icon.svg", s.favicon],
    ["apps/web/public/icons/icon.svg", s.pwaIcon],
    ["docs/assets/logo-light.svg", s.wordmark(INK) + "\n"],
    ["docs/assets/logo-dark.svg", s.wordmark(PAPER) + "\n"],
    [mobile, splice(read(mobile), mobile, between, mobileBlock(brand))],
    [cli, splice(read(cli), cli, CLI_SVG, s.cliWordmark)],
  ];
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
}

export async function sync(root, { check = false } = {}) {
  const drifted = [];
  for (const [rel, want] of await targets(root)) {
    const file = join(root, rel);
    let have = null;
    try {
      have = readFileSync(file, "utf8");
    } catch {}
    // Compare with line endings normalised: the worktree may hold CRLF while the
    // generated copy uses LF, and that difference is not drift.
    if (have !== null && have.replace(/\r\n/g, "\n") === want.replace(/\r\n/g, "\n")) continue;
    drifted.push(rel);
    if (!check) writeFileSync(file, want);
  }
  return drifted;
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const rootAt = args.indexOf("--root");
  const root = rootAt >= 0 ? resolve(args[rootAt + 1]) : resolve(dirname(fileURLToPath(import.meta.url)), "../..");
  const drifted = await sync(root, { check });
  if (check && drifted.length) {
    console.error(`Out of sync with packages/ui/lib/morechat-brand.ts:\n${drifted.map((f) => `  ${f}`).join("\n")}\nRun: node scripts/brand/sync.mjs`);
    process.exit(1);
  }
  console.log(drifted.length ? `updated ${drifted.join(", ")}` : "brand copies in sync");
}
