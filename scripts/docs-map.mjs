#!/usr/bin/env node
/**
 * docs-map.mjs — the documentation index and its gatekeeper (P0.5).
 *
 *   node scripts/docs-map.mjs --build   rewrite docs/MAP.json and the index
 *                                       section of docs/README.md
 *   node scripts/docs-map.mjs --check   verify front-matter, links, staleness
 *                                       and index coverage; exit 1 on problems
 *
 * Why a script instead of a hand-maintained index: docs/ holds ~150 documents
 * across eight directories, and every hand-managed table of contents in this
 * repository has drifted from the files within a day. The index is therefore
 * generated, and `--check` fails the moment the two disagree.
 *
 * What `--check` enforces:
 *
 *   1. every `docs/**.md` outside `docs/archive/**` opens with a front-matter
 *      block carrying purpose / owner / status / updated / related, where
 *      status is one of the closed set below and updated is YYYY-MM-DD;
 *   2. no relative link inside docs/ resolves to a path that does not exist,
 *      and no `related` entry points at a missing document;
 *   3. a document whose status is `current` was updated within STALE_DAYS —
 *      "current" is a claim about freshness, so it has to expire;
 *   4. every document is reachable from the index: docs/MAP.json must list it,
 *      and the generated section of docs/README.md must be byte-identical to a
 *      fresh render. A new document that was never indexed fails here.
 *
 * Links outside the docs/ tree are reported but not enforced: this file owns the
 * docs map, not the whole repository's link hygiene.
 *
 * Front-matter is a deliberately small YAML subset (scalars, inline empty list,
 * and block lists of scalars) so this script needs no dependency: the front-matter
 * is written by tooling in exactly that shape.
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, "..");
const DOCS_DIR = join(ROOT, "docs");
const MAP_PATH = join(DOCS_DIR, "MAP.json");
const README_PATH = join(DOCS_DIR, "README.md");

/** Directories under docs/ that are history, not navigation targets. */
const SKIP_DIRS = new Set(["archive", "node_modules"]);

const REQUIRED_KEYS = ["purpose", "owner", "status", "updated", "related"];
const STATUSES = new Set(["current", "draft", "reference", "historical", "deprecated"]);
const STALE_DAYS = 90;

const INDEX_BEGIN = "<!-- docs-map:index:begin | generated by scripts/docs-map.mjs — do not edit by hand -->";
const INDEX_END = "<!-- docs-map:index:end -->";
const INDEX_HEADING = "## 文档索引（由脚本生成，勿手改）";

// ---------------------------------------------------------------------------
// walking and parsing
// ---------------------------------------------------------------------------

function toPosix(p) {
  return p.split(sep).join("/");
}

function listDocs() {
  const out = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (SKIP_DIRS.has(entry.name)) continue;
        walk(path);
        continue;
      }
      if (extname(entry.name) !== ".md") continue;
      out.push(toPosix(relative(ROOT, path)));
    }
  };
  walk(DOCS_DIR);
  out.sort();
  return out;
}

/**
 * Parses the small YAML subset the front-matter uses. Returns null when the file
 * has no front-matter block at all, so "absent" stays distinguishable from
 * "present but empty".
 */
function parseFrontMatter(text) {
  const normalized = text.replace(/^\uFEFF/, "");
  if (!normalized.startsWith("---\n") && !normalized.startsWith("---\r\n")) return null;
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(normalized);
  if (!match) return null;

  const data = {};
  let currentList = null;
  for (const rawLine of match[1].split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, "");
    if (line === "" || line.startsWith("#")) continue;
    const item = /^\s+-\s*(.*)$/.exec(line);
    if (item && currentList) {
      data[currentList].push(unquote(item[1]));
      continue;
    }
    const entry = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (!entry) continue;
    const [, key, value] = entry;
    if (value === "") {
      data[key] = [];
      currentList = key;
      continue;
    }
    currentList = null;
    data[key] = value === "[]" ? [] : unquote(value);
  }
  return { data, body: normalized.slice(match[0].length), offset: match[0].length };
}

/**
 * Removes the generated index block from a document body. The index is a
 * rendering of this map, so letting its links back into the link graph would
 * make every document "linked from README" and create an index that can never
 * stabilize: each build would change the fingerprint that --check compares.
 */
function stripGeneratedIndex(body) {
  const start = body.indexOf(INDEX_BEGIN);
  const end = body.indexOf(INDEX_END);
  if (start < 0 || end < start) return body;
  return body.slice(0, start) + body.slice(end + INDEX_END.length);
}

function unquote(value) {  const trimmed = value.trim();
  if (trimmed.length >= 2 && trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return trimmed.slice(1, -1).replace(/\\"/g, '"');
  }
  if (trimmed.length >= 2 && trimmed.startsWith("'") && trimmed.endsWith("'")) {
    return trimmed.slice(1, -1).replace(/''/g, "'");
  }
  return trimmed;
}

function titleOf(body) {
  const match = /^#\s+(.+)$/m.exec(body);
  return match ? match[1].trim() : "";
}

/** Markdown inline links plus bare autolinks, as raw targets. */
function linkTargets(body) {
  const targets = [];
  const seen = new Set();
  const push = (target) => {
    if (!target || seen.has(target)) return;
    seen.add(target);
    targets.push(target);
  };
  for (const match of body.matchAll(/\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
    push(match[1]);
  }
  for (const match of body.matchAll(/^ {0,3}\[[^\]]+\]:\s*(\S+)/gm)) {
    push(match[1]);
  }
  return targets;
}

function isExternal(target) {
  return /^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith("//");
}

/**
 * Resolves a link or front-matter entry against the document that contains it.
 * Returns { path } in repo-relative posix form, or null when the target is
 * external, a pure anchor, or already covered by the skip list.
 */
function resolveTarget(docPath, target) {
  const withoutAnchor = target.split("#")[0];
  if (withoutAnchor === "") return null;
  if (isExternal(withoutAnchor)) return null;
  if (isAbsolute(withoutAnchor)) return null;
  const decoded = decodeURI(withoutAnchor);
  const absolute = resolve(dirname(join(ROOT, docPath)), decoded);
  return toPosix(relative(ROOT, absolute));
}

// ---------------------------------------------------------------------------
// the map
// ---------------------------------------------------------------------------

function buildMap() {
  const docs = [];
  const problems = [];
  const deadLinks = new Map(); // "doc -> target"

  for (const path of listDocs()) {
    const text = readFileSync(join(ROOT, path), "utf8");
    const front = parseFrontMatter(text);
    const body = stripGeneratedIndex(front ? front.body : text);
    const entry = {
      path,
      title: titleOf(body),
      purpose: "",
      owner: "",
      status: "",
      updated: "",
      related: [],
      links_out: [],
      links_in: [],
    };

    if (!front) {
      problems.push(`${path}: missing front-matter`);
    } else {
      entry.purpose = scalar(front.data.purpose);
      entry.owner = scalar(front.data.owner);
      entry.status = scalar(front.data.status);
      entry.updated = scalar(front.data.updated);
      entry.related = Array.isArray(front.data.related) ? front.data.related : [];
    }

    const outbound = new Set();
    for (const target of linkTargets(body)) {
      const resolved = resolveTarget(path, target);
      if (!resolved) continue;
      if (!resolved.startsWith("docs/")) continue; // outside this file's remit
      const exists = existsSync(join(ROOT, resolved)) || existsSync(join(ROOT, resolved, "index.md"));
      if (!exists) {
        deadLinks.set(`${path} -> ${resolved}`, true);
        continue;
      }
      if (resolved.endsWith(".md")) outbound.add(resolved);
    }
    for (const target of entry.related) {
      // `related` entries are repo-relative ("docs/plans/PLAN.md"), unlike a
      // body link which is relative to the document that contains it.
      const resolved = target.startsWith("docs/")
        ? toPosix(join(...target.split("/")))
        : resolveTarget(path, target);
      if (!resolved) continue;
      if (!existsSync(join(ROOT, resolved))) {
        deadLinks.set(`${path} -> related ${resolved}`, true);
        continue;
      }
      if (resolved.endsWith(".md")) outbound.add(resolved);
    }
    entry.links_out = [...outbound].sort();
    docs.push(entry);
  }

  const byPath = new Map(docs.map((doc) => [doc.path, doc]));
  for (const doc of docs) {
    for (const target of doc.links_out) {
      const targetDoc = byPath.get(target);
      if (targetDoc && target !== doc.path) targetDoc.links_in.push(doc.path);
    }
  }
  for (const doc of docs) doc.links_in.sort();

  const fingerprint = createHash("sha256")
    .update(JSON.stringify(docs))
    .digest("hex");

  return {
    schema: 1,
    generated_by: "scripts/docs-map.mjs",
    docs_root: "docs",
    skipped: ["docs/archive/**"],
    count: docs.length,
    fingerprint,
    docs,
    problems,
    dead_links: [...deadLinks.keys()].sort(),
  };
}

function scalar(value) {
  if (Array.isArray(value)) return value.join(",");
  return typeof value === "string" ? value : "";
}

// ---------------------------------------------------------------------------
// index rendering
// ---------------------------------------------------------------------------

function renderIndex(map) {
  const groups = new Map();
  for (const doc of map.docs) {
    const rest = doc.path.slice("docs/".length);
    const group = rest.includes("/") ? rest.split("/")[0] : "";
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(doc);
  }
  const order = [...groups.keys()].sort((a, b) => (a === "" ? -1 : b === "" ? 1 : a.localeCompare(b)));

  const lines = [];
  for (const group of order) {
    const label = group === "" ? "根目录" : group;
    lines.push(`### ${label}`, "");
    lines.push("| 文档 | purpose | owner | status | updated |");
    lines.push("|---|---|---|---|---|");
    for (const doc of groups.get(group)) {
      const link = doc.path.slice("docs/".length);
      const href = link === "README.md" ? "README.md" : link;
      const cells = [doc.purpose, doc.owner, doc.status, doc.updated].map((cell) => escapeCell(cell));
      lines.push(`| [${escapeCell(doc.title || doc.path)}](${href}) | ${cells.join(" | ")} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

function escapeCell(value) {
  return String(value ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function indexBlock(map) {
  return `${INDEX_BEGIN}\n\n${renderIndex(map)}\n${INDEX_END}`;
}

function readmeWithIndex(map) {
  const text = readFileSync(README_PATH, "utf8");
  const start = text.indexOf(INDEX_BEGIN);
  const end = text.indexOf(INDEX_END);
  if (start >= 0 && end > start) {
    return text.slice(0, start) + indexBlock(map) + text.slice(end + INDEX_END.length);
  }
  const separator = text.endsWith("\n") ? "\n" : "\n\n";
  return `${text}${separator}${INDEX_HEADING}\n\n${indexBlock(map)}\n`;
}

// ---------------------------------------------------------------------------
// build / check
// ---------------------------------------------------------------------------

function build() {
  const map = buildMap();
  writeFileSync(MAP_PATH, `${JSON.stringify(map, null, 2)}\n`, "utf8");
  writeFileSync(README_PATH, readmeWithIndex(map), "utf8");
  console.log(`docs-map: wrote docs/MAP.json (${map.count} documents) and the README index`);
  if (map.dead_links.length) {
    console.log(`docs-map: ${map.dead_links.length} pre-existing dead link(s) recorded, not fixed by this run`);
  }
  return 0;
}

function check() {
  const errors = [];
  const map = buildMap();
  errors.push(...map.problems);

  if (!existsSync(MAP_PATH)) {
    errors.push("docs/MAP.json is missing — run node scripts/docs-map.mjs --build");
  } else {
    const recorded = JSON.parse(readFileSync(MAP_PATH, "utf8"));
    if (recorded.fingerprint !== map.fingerprint) {
      const indexed = new Set((recorded.docs ?? []).map((doc) => doc.path));
      for (const doc of map.docs) {
        if (!indexed.has(doc.path)) {
          errors.push(`${doc.path}: not referenced by the generated index (docs/MAP.json) — run --build`);
        }
      }
      for (const doc of recorded.docs ?? []) {
        if (!map.docs.some((current) => current.path === doc.path)) {
          errors.push(`${doc.path}: indexed but no longer exists — run --build`);
        }
      }
      if (!errors.some((error) => error.includes("docs/MAP.json"))) {
        errors.push("docs/MAP.json is stale (front-matter or documents changed) — run --build");
      }
    }
    const deadLinks = new Set(map.dead_links);
    for (const link of recorded.dead_links ?? []) {
      if (!deadLinks.has(link)) {
        errors.push(`${link}: recorded as dead in docs/MAP.json but now resolves — run --build`);
      }
    }
  }

  for (const doc of map.docs) {
    if (!doc.status) continue;
    if (!STATUSES.has(doc.status)) {
      errors.push(`${doc.path}: status "${doc.status}" is not one of ${[...STATUSES].join(", ")}`);
    }
    if (!doc.updated) continue;
    const updated = Date.parse(`${doc.updated}T00:00:00Z`);
    if (Number.isNaN(updated)) {
      errors.push(`${doc.path}: updated "${doc.updated}" is not YYYY-MM-DD`);
      continue;
    }
    if (doc.status === "current") {
      const ageDays = (Date.now() - updated) / 86_400_000;
      if (ageDays > STALE_DAYS) {
        errors.push(
          `${doc.path}: status current but last updated ${Math.floor(ageDays)} days ago ` +
            `(> ${STALE_DAYS}); refresh it or change the status`,
        );
      }
    }
  }

  const readme = existsSync(README_PATH) ? readFileSync(README_PATH, "utf8") : "";
  const start = readme.indexOf(INDEX_BEGIN);
  const end = readme.indexOf(INDEX_END);
  if (start < 0 || end < start) {
    errors.push("docs/README.md: generated index section is missing — run --build");
  } else if (readme.slice(start, end + INDEX_END.length) !== indexBlock(map)) {
    errors.push("docs/README.md: generated index section is stale — run --build");
  }

  for (const error of errors) console.error(`docs-map: ${error}`);
  const orphans = map.docs.filter((doc) => doc.links_in.length === 0 && doc.path !== "docs/README.md");
  if (orphans.length) {
    console.log(`docs-map: ${orphans.length} document(s) with no inbound link from another document (warning only)`);
  }
  if (map.dead_links.length) {
    console.log(`docs-map: ${map.dead_links.length} known dead link(s) grandfathered by docs/MAP.json`);
  }
  if (errors.length) {
    console.error(`docs-map: ${errors.length} problem(s)`);
    return 1;
  }
  console.log(`docs-map: ${map.count} documents OK (front-matter, links, index, staleness)`);
  return 0;
}

function usage() {
  console.error("usage: node scripts/docs-map.mjs <--build|--check>");
  return 2;
}

const args = new Set(process.argv.slice(2));
if (args.has("--build")) process.exit(build());
else if (args.has("--check")) process.exit(check());
else process.exit(usage());
