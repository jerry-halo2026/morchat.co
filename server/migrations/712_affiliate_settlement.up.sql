-- Affiliate settlement: one periodic statement the platform issues for this
-- workspace (docs/engineering/WORKBENCH-API.md §11). T+N or monthly, covering a
-- period — not one row per pick, because the platform settles in cycles and the
-- statement is the unit that is paid.
--
-- `net_amount = gross_commission − tech_service_fee − refund_deduction` is the
-- platform's own arithmetic. The server stores all four and never recomputes or
-- overwrites `net_amount` from the other three: the platform rounds, applies
-- campaign adjustments and occasionally settles a period we would have summed
-- differently, and a recomputed net would silently disagree with the money that
-- actually arrived. The identity is documentation, not a write rule.
--
-- `external_no` is the platform's statement number. It is the only column that
-- can tie our row back to the statement, so it is nullable (an import may not
-- have it yet) but never generated by us.
--
-- `status` is the payment state of the whole statement; `paid_at` is the day the
-- money arrived and is NULL until it does. There is no `archived_at` and no
-- delete route: a settlement is a platform fact, and a wrong row is corrected by
-- PATCH (status / amounts / note), not removed. A period that has to be
-- re-issued arrives as a new statement with its own `external_no`.
CREATE TABLE affiliate_settlement (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id UUID NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    gross_commission NUMERIC(14,2) NOT NULL DEFAULT 0,
    tech_service_fee NUMERIC(14,2) NOT NULL DEFAULT 0,
    refund_deduction NUMERIC(14,2) NOT NULL DEFAULT 0,
    net_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    currency CHAR(3) NOT NULL DEFAULT 'CNY',
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'failed')),
    paid_at DATE,
    external_no TEXT,
    note TEXT,
    created_by UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT affiliate_settlement_period_check CHECK (period_end >= period_start)
);
